import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const base = fileURLToPath(new URL('..', import.meta.url));
const read = p => readFileSync(join(base,p),'utf8');
const fromSource = async path =>
  import('data:text/javascript;base64,'+Buffer.from(read(path)).toString('base64'));
const {clientValue,surveyScore} = await fromSource('public/assets/js/grc-formulas.js');
const {EXERCISE_GROUPS,calculateGroups} = await fromSource('public/assets/js/grc-group-engine.js');
assert.equal(EXERCISE_GROUPS.length,12);
assert.equal(calculateGroups([{id:'A',clients:2,orders:4,revenue:100000}]).basket,25000);
assert.throws(()=>calculateGroups([{id:'A',clients:-1,orders:0,revenue:0}]));
assert.throws(()=>calculateGroups([{id:'A',clients:1,orders:1,revenue:2},{id:'A',clients:1,orders:1,revenue:2}]));
assert.ok(Math.abs(clientValue(100000,80,30,10000,0).net - 140000) < 1e-7);
assert.throws(()=>clientValue(100000,100,30,10000,0));
assert.equal(surveyScore([{rating:5,recommendation:10},{rating:4,recommendation:6}]).nps,0);
assert.equal(surveyScore([]),null);
const source=read('public/assets/js/app.js');
const admin=read('public/assets/js/admin.js');
const php=read('app/Controllers/ApiController.php');
const security=read('app/Core/Security.php');
const html=read('public/admin.html');
const module=read('public/assets/js/grc-analyses.js');
assert.match(source,/admin-analyses/);
assert.match(source,/view=analyses/);
assert.match(admin,/mountGrcInsights/);
assert.match(php,/\['GET', '\/admin\/insights', 'admin'/);
assert.match(security,/admin\/insights/);
assert.match(html,/grc-analyses\.css/);
assert.match(module,/\{ passive: true \}/);
assert.match(module,/5000/);
assert.match(module,/mountGroupCalculations/);
assert.match(module,/Fréquence moyenne d’achat/);
assert.match(module,/Durée de vie moyenne d’un client/);
assert.match(module,/Récence \(mois\)/);
assert.match(module,/row\.months === null/);
assert.doesNotMatch(module,/row\.days \+ ' j'/);
assert.doesNotMatch(module,/13 et plus|11[-–]9|7[-–]5|3 et moins/);
console.log('OK — modules GRC, accès admin et vues intégrées');
