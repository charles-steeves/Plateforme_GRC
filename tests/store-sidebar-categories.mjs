import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const read = file => readFileSync(join(root, file), 'utf8');
const app = read('public/assets/js/app.js');
const shop = read('public/assets/js/shop.js');
const admin = read('public/assets/js/admin.js');
const css = read('public/assets/css/site.css');
assert.match(app, /function renderStoreNav\(user\)/);
assert.match(app, /'aria-controls': 'store-sidebar-menu'/);
assert.match(app, /store-sidebar-collapsed/);
assert.match(app, /'Escape'/);
assert.match(app, /Mes commandes/);
assert.match(app, /Ma fidélité/);
assert.match(app, /Service client/);
assert.match(app, /store-account-details/);
assert.match(app, /if \(isAdminPage\) renderAdminNav\(signedInUser\)/);
assert.match(css, /--store-sidebar-width: 208px/);
assert.match(css, /body\.store-workspace\.store-sidebar-collapsed/);
assert.match(css, /@media \(max-width: 900px\)/);
assert.match(shop, /el\('select', \{ id: 'catalogue-category', name: 'category' \}/);
assert.doesNotMatch(shop, /el\('input', \{ id: 'catalogue-category'/);
assert.match(shop, /api\('\/products\/categories'\)/);
assert.match(shop, /id: 'catalogue-filters'/);
assert.match(admin, /el\('select', \{ id: 'product-category', name: 'category'/);
assert.match(admin, /'Créer la catégorie'/);
assert.match(admin, /api\('\/admin\/categories', \{ method: 'POST'/);
assert.match(admin, /selectProductOnMobile\(product\)/);
assert.match(admin, /api\('\/admin\/categories'\)/);
assert.match(read('public/assets/js/customer.js'), /id: 'mes-commandes'/);
assert.match(read('public/assets/js/customer.js'), /id: 'ma-fidelite'/);
console.log('OK — shop sidebar, cart/client navigation and controlled product groups');
