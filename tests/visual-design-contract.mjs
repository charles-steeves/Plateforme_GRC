import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
const root = fileURLToPath(new URL('..', import.meta.url));
const read = path => readFileSync(join(root, path), 'utf8');
const css = read('public/assets/css/site.css');
const shop = read('public/assets/js/shop.js');
const admin = read('public/assets/js/admin.js');
const grc = read('app/Repositories/GrcRepository.php');
const app = read('public/assets/js/app.js');
assert.match(css, /\.site-header\s*\{\s*background:\s*linear-gradient/);
assert.match(css, /body\.admin-workspace \.site-header/);
assert.match(css, /\.header-actions \.button-primary/);
assert.match(css, /\.category-browse-grid/);
assert.match(css, /\.dashboard-charts/);
assert.match(css, /\.chart-donut-layout/);
assert.match(css, /\.chart-trend-row progress/);
assert.match(css, /@media \(max-width: 550px\)/);
assert.match(shop, /'category-browse-card'/);
assert.match(shop, /categoryBrowse, form, results/);
assert.match(shop, /'Explorer le catalogue'/);
assert.match(admin, /function statusChart\(counts\)/);
assert.match(admin, /function trendChart\(rows\)/);
assert.match(admin, /document\.createElementNS/);
assert.match(admin, /orders_last_7_days/);
assert.match(grc, /COUNT\(\*\) AS total/);
assert.match(grc, /'orders_last_7_days'/);
assert.match(app, /user\?\.role === 'admin' \? \[\['\/admin\.html'/);
assert.match(app, /user\?\.role === 'admin' \? navLink\('Administration'/);
console.log('OK — lively storefront + data-driven administrator charts + role-gated nav');
